use odferrous::TextDocument;
use std::path::Path;

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let mut doc = TextDocument::new_flat();
    doc.add_heading("Sample Document");
    doc.add_paragraph("This is a test generated by odferrous for LibreOffice.");

    let fodt = Path::new("sample.fodt");
    doc.save_as_flat(fodt)?;
    println!("Wrote {}", fodt.display());

    // now write ODT package
    let mut doc2 = TextDocument::open(fodt)?;
    let odt = Path::new("sample.odt");
    doc2.save_as_package(odt)?;
    println!("Wrote {}", odt.display());

    Ok(())
}
